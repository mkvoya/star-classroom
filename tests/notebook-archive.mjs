import assert from 'node:assert/strict';
import { unzipSync, strFromU8 } from 'fflate';
import { notebookArchive } from '../lib/notebook-archive.ts';
const base={id:'same-id',room:'123456',owner:'never-export-this-key',student:'20260001 张同学',name:'HW01.ipynb',receivedAt:'2026-11-03T03:00:00Z'};
const one=JSON.stringify({nbformat:4,cells:[{source:['你好']}]}),two=JSON.stringify({nbformat:4,cells:[{source:['重交']}]} );
const receipts=[{...base,size:one.length,blob:new Blob([one])},{...base,size:two.length,blob:new Blob([two])},{...base,id:'../../bad',student:'../同学/名字',name:'../../作业.ipynb',size:0,blob:new Blob([])}];
const progress=[];
const blob=await notebookArchive(receipts,n=>progress.push(n));
const entries=unzipSync(new Uint8Array(await blob.arrayBuffer()));
assert.deepEqual(progress,[1,2,3]);
const manifest=JSON.parse(strFromU8(entries['提交清单.json']));
assert.equal(Object.keys(entries).length,4);
assert.notEqual(manifest[0].path,manifest[1].path);
assert.equal(strFromU8(entries[manifest[0].path]),one);
assert.equal(strFromU8(entries[manifest[1].path]),two);
assert.equal(entries[manifest[2].path].length,0);
assert.ok(Object.keys(entries).every(p=>!p.split('/').includes('..')));
assert.ok(!strFromU8(entries['提交清单.json']).includes(base.owner));
await assert.rejects(()=>notebookArchive([]));
console.log('PASS: ZIP extraction, Chinese names, duplicate submissions, safe paths, empty files, manifest and progress.');
