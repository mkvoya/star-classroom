import assert from 'node:assert/strict';
import { fileView, updateFiles } from '../lib/file-signaling.ts';
const now=100000;
const open=()=>updateFiles(undefined,{action:'files-open',session:'session-a'},true,undefined,now);
assert.throws(()=>updateFiles(undefined,{action:'files-open',session:'x'},false,'student',now));
let state=open();
assert.equal(fileView(state,false,'s',true,now+20000).session,null);
assert.throws(()=>updateFiles(state,{action:'files-pulse',session:'session-a'},false,'s',now));
assert.throws(()=>updateFiles(state,{action:'files-pulse',session:'wrong'},true,undefined,now));
assert.throws(()=>updateFiles(state,{action:'files-pulse',session:'session-a'},true,undefined,now+20000));
state=updateFiles(state,{action:'files-offer',session:'session-a',id:'transfer-a',sdp:'v=0\r\nprivate-offer'},false,'student-a',now);
assert.equal(fileView(state,false,'student-b',true,now).signals.length,0);
assert.equal(fileView(state,true,undefined,false,now).signals.length,0);
assert.equal(fileView(state,true,undefined,true,now).signals.length,1);
assert.throws(()=>updateFiles(state,{action:'files-answer',session:'session-a',id:'transfer-a',memberId:'student-a',sdp:'v=0\r\nanswer'},false,'student-b',now));
state=updateFiles(state,{action:'files-answer',session:'session-a',id:'transfer-a',memberId:'student-a',sdp:'v=0\r\nanswer'},true,undefined,now);
assert.equal(fileView(state,false,'student-a',true,now).signals[0].answer,'v=0\r\nanswer');
assert.throws(()=>updateFiles(state,{action:'files-offer',session:'session-a',id:'big',sdp:'v=0'+ 'a'.repeat(12000)},false,'student-a',now));
state=updateFiles(state,{action:'files-open',session:'session-b'},true,undefined,now);
assert.equal(Object.keys(state.signals).length,0);
assert.throws(()=>updateFiles(state,{action:'files-close',session:'session-a'},true,undefined,now));
assert.equal(updateFiles(state,{action:'files-close',session:'session-b'},true,undefined,now),undefined);
console.log('PASS: teacher-only controls, lease expiry, private signaling, stale sessions, payload limits, session reset.');
